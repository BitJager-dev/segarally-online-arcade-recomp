#!/usr/bin/env python3
"""Lift the code SEGA Rally's MultiStream audio SPU program loads at run time.

MultiStream (the 69 KB SPU image) DMAs four more programs into its own local
store and calls into them:
  - flashATRAC.pic from /dev_flash (the ATRAC decoder), code at LS 0x30780,
  - three of the game's own SPU images: spu_aef18824... at LS 0x2F880, and
    spu_773a6898... and spu_ecd8b074..., which take turns at LS 0x2D680.
None of them runs at its link address, so their lifted copies (if any) do not
apply. This lifts each one at the address it runs at, under an image id of its
own, and writes overlays_register.c, which registers the functions and the code
bytes with spu_overlay_register_static(): a dispatch miss in MultiStream inside
one of those spans compares local store with the bytes once and, on a match,
runs the lifted code from then on (interpreted otherwise).

    lift_spu_overlays.py --pic <dev_flash>/sys/external/flashATRAC.pic \\
        --spu-dir analysis/spu_programs --out <build>/generated_spu_ovl

Inputs are your firmware and game; the output goes to the build tree only.
"""
import argparse
import hashlib
import json
import os
import struct
import subprocess
import sys

OWNER_IMAGE_ID = 342301998   # MultiStream (spu_4671d2e3...), as build_spu_workloads.py names it

# name, source, LS - vaddr, image id, LS ranges left out of the byte check, entry points.
# MultiStream enters each through addresses it computes (a table it reads from the loaded
# code), so the function finder cannot see them; these are the ones a run reaches
# (SPU_UNLIFTED_LOG). One missing here is not fatal: it runs interpreted up to the next
# lifted function.
OVERLAYS = [
    ("flashatrac", "pic", 0x30700, 0x51A70001, [(0x35B50, 0x35B60)],   # a variable inside .text
     [0x30790]),
    ("ms_aef18824", "aef188249220d6de", 0x2F800, 0x51A70002, [], [0x2F890, 0x2F898, 0x2FBD0]),
    ("ms_773a6898", "773a689875af1617", 0x2D600, 0x51A70003, [],
     [0x2D690, 0x2D6A0, 0x2D910, 0x2DAB0, 0x2E250]),
    # Takes turns with ms_773a6898 in the same local store.
    ("ms_ecd8b074", "ecd8b0741f2db7db", 0x2D600, 0x51A70004, [], [0x2D690, 0x2D6A0, 0x2D910]),
]


def text_segment(elf):
    phoff, = struct.unpack_from(">I", elf, 0x1C)
    phnum, = struct.unpack_from(">H", elf, 0x2C)
    for i in range(phnum):
        p_type, off, va, _pa, filesz, _memsz, flags, _al = struct.unpack_from(">8I", elf, phoff + i * 32)
        if p_type == 1 and flags & 1 and filesz:
            return off, va, filesz
    sys.exit("no executable segment")


def find_image(spu_dir, prefix):
    for f in sorted(os.listdir(spu_dir)):
        if f.endswith(".elf"):
            data = open(os.path.join(spu_dir, f), "rb").read()
            if hashlib.sha256(data).hexdigest().startswith(prefix):
                return data
    sys.exit(f"no SPU image with sha256 {prefix}... in {spu_dir}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pic", required=True)
    ap.add_argument("--spu-dir", required=True, help="the extracted SPU images (analysis/spu_programs)")
    ap.add_argument("--out", required=True)
    tools = os.environ.get("PS3RECOMP_TOOLS", os.path.join(os.path.dirname(__file__), "..", "..", "deps", "ps3recomp", "tools"))
    ap.add_argument("--tools", default=tools)
    args = ap.parse_args()
    sys.path.insert(0, args.tools)
    from find_spu_functions import detect_functions
    from build_spu_workloads import debase_includes

    os.makedirs(args.out, exist_ok=True)
    reg = ['/* GENERATED by tools/lift_spu_overlays.py -- MultiStream\'s run-time code. */',
           '#include <stdint.h>', '#include "spu_overlay_residency.h"',
           'extern void spu_begin_image(int image_id);']
    body, sources = [], []
    for name, src, delta, image_id, holes, entries in OVERLAYS:
        elf = open(args.pic, "rb").read() if src == "pic" else find_image(args.spu_dir, src)
        off, va, size = text_segment(elf)
        lsa = va + delta
        funcs, (code_off, base, code_size) = detect_functions(elf, base_override=lsa, verbose=False)
        assert base == lsa and code_off == off and code_size == size, (name, hex(base), hex(lsa))
        d = os.path.join(args.out, name)
        os.makedirs(d, exist_ok=True)
        code = elf[off:off + size]
        open(os.path.join(d, "code.bin"), "wb").write(code)
        json.dump([dict(start=s, end=e) for s, e in funcs], open(os.path.join(d, "functions.json"), "w"))
        prefix = f"ovl_{name}_"
        cmd = [sys.executable, os.path.join(args.tools, "spu_lifter.py"), os.path.join(d, "code.bin"),
               "--base", str(lsa), "--functions", os.path.join(d, "functions.json"),
               "--symbol-prefix", prefix, "--external-calls",
               "--extra-funcs", ",".join(hex(a) for a in entries),
               "--report", os.path.join(d, "lift.json"), "--output", d]
        r = subprocess.run(cmd, capture_output=True, text=True)
        open(os.path.join(d, "lift.log"), "w").write(r.stdout + r.stderr)
        if r.returncode:
            sys.exit(f"lifting {name} failed; see {d}/lift.log")
        rep = json.load(open(os.path.join(d, "lift.json")))
        if set(rep["unsupported"]) - {".word"}:
            sys.exit(f"{name}: unsupported instructions {rep['unsupported']}")
        starts = {s for s, _ in rep["functions"]}
        missing = (set(rep["call_targets"]) | set(rep["branch_targets"])) - starts
        if missing:
            sys.exit(f"{name}: branch targets without functions: {sorted(hex(m) for m in missing)}")
        for fn in ("spu_recomp.c", "spu_recomp.h"):
            debase_includes(os.path.join(d, fn))
        sources.append(os.path.join(d, "spu_recomp.c"))
        print(f"{name}: {len(rep['functions'])} functions at LS 0x{lsa:05X} (+0x{size:X}), "
              f"{len(rep.get('external_targets', []))} external targets, image {image_id}")

        # The byte check: the code minus the holes, as at most 8 segments.
        segs, cur = [], lsa
        for h0, h1 in sorted(holes) + [(lsa + size, lsa + size)]:
            if h0 > cur:
                segs.append((cur, h0))
            cur = max(cur, h1)
        reg.append(f"extern void {prefix}spu_recomp_register(void);")
        for i, (s, e) in enumerate(segs):
            b = code[s - lsa:e - lsa]
            rows = ",\n".join("    " + ",".join(f"0x{x:02X}" for x in b[k:k + 24]) for k in range(0, len(b), 24))
            reg.append(f"static const uint8_t {name}_seg{i}[{len(b)}] = {{\n{rows}\n}};")
        segl = ", ".join(f"{{0x{s:X}u, {e - s}u, {name}_seg{i}}}" for i, (s, e) in enumerate(segs))
        body.append(f"    spu_begin_image({image_id}); {prefix}spu_recomp_register();")
        body.append(f"    {{ static const spu_overlay_code_segment c[] = {{ {segl} }};")
        body.append(f"      spu_overlay_register_static({OWNER_IMAGE_ID}, 0x{lsa:X}u, 0x{size:X}u, {image_id}, c, "
                    f"{len(segs)}); }}")
    reg.append("__attribute__((constructor)) static void spu_overlays_register(void)\n{")
    reg += body
    reg.append("    spu_begin_image(0);\n}")
    open(os.path.join(args.out, "overlays_register.c"), "w").write("\n".join(reg) + "\n")
    sources.append(os.path.join(args.out, "overlays_register.c"))
    open(os.path.join(args.out, "sources.cmake"), "w").write(
        "set(SPU_OVERLAY_SOURCES\n" + "".join(f'    "{s}"\n' for s in sources) + ")\n")


if __name__ == "__main__":
    main()
